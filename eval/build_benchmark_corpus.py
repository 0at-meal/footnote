def build_and_save_corpus() -> AccessionCorpusManifest:
    LABELS_DIR.mkdir(parents=True, exist_ok=True)
    filings = create_corpus_data()

    dev_count = sum(1 for f in filings if f.split == CorpusSplit.dev)
    test_count = sum(1 for f in filings if f.split == CorpusSplit.test)
    double_labeled_count = sum(1 for f in filings if f.double_labeled)

    manifest = AccessionCorpusManifest(
        corpus_name="Footnote 40-Filing Benchmark Corpus",
        corpus_version="2.0.0",
        total_filings=len(filings),
        dev_count=dev_count,
        test_count=test_count,
        double_labeled_count=double_labeled_count,
        filing_accessions=[f.accession_number for f in filings],
    )

    # Save manifest
    manifest_path = LABELS_DIR / "manifest.json"
    manifest_path.write_text(json.dumps(manifest.model_dump(), indent=2), encoding="utf-8")

    # Save individual label files
    for filing in filings:
        file_path = LABELS_DIR / f"{filing.accession_number}.json"
        file_path.write_text(json.dumps(filing.model_dump(), indent=2), encoding="utf-8")

    print(f"Successfully generated {len(filings)} accession labels in {LABELS_DIR}")
    print(f"Dev count: {dev_count}, Test count: {test_count}, Double-labeled: {double_labeled_count}")
    return manifest


if __name__ == "__main__":
    build_and_save_corpus()
